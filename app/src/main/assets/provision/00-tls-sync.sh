#!/data/data/com.termux/files/usr/bin/bash
# Step 0: make HTTPS work inside Termux before anything tries to download.
#
# Every TLS client in the Termux prefix verifies against ONE file, $PREFIX/etc/tls/cert.pem:
#   * curl    - compiled-in CA bundle path
#   * python  - ssl.get_default_verify_paths().openssl_cafile
#   * apt     - the GnuTLS build embeds the same path
# so updating that single file is enough (no environment variables needed, which also means we
# never leak a host path into the proot container).
#
# On corporate networks that intercept TLS, the anchor is a private CA installed on Android as a
# *user* certificate. TlsTrustSync has already written those anchors to opencode-anchors.pem; here
# we merge them into the bundle and confirm verification actually passes.
PREFIX="${PREFIX:-/data/data/com.termux/files/usr}"
TLS="$PREFIX/etc/tls"
ANCHORS="$TLS/opencode-anchors.pem"
EXTRA="$TLS/extra-anchors.pem"
BUNDLE="$TLS/cert.pem"
PRISTINE="$TLS/cert.pem.pristine"
MARK='# OpenCode TLS anchors (managed) - regenerated by setup'

mkdir -p "$TLS"
[ -f "$ANCHORS" ] || : > "$ANCHORS"
[ -f "$EXTRA" ] || : > "$EXTRA"

# Capture the bootstrap's public-CA bundle exactly once, before our anchors are merged in. Without
# this, re-running setup would append the anchors again on every attempt.
if [ -f "$BUNDLE" ] && ! grep -q 'OpenCode TLS anchors (managed)' "$BUNDLE" 2>/dev/null; then
    cp "$BUNDLE" "$PRISTINE"
fi
[ -f "$PRISTINE" ] || : > "$PRISTINE"

{
    echo "$MARK"
    cat "$PRISTINE"
    cat "$ANCHORS"
    # Anchors the user dropped in by hand - a corporate root CA lives in the machine's certificate
    # store, never in Android's, so this is the only way to make TLS inspection work here.
    cat "$EXTRA"
} > "$BUNDLE.tmp" && mv "$BUNDLE.tmp" "$BUNDLE"

echo "Termux trust bundle: $(grep -c 'BEGIN CERTIFICATE' "$BUNDLE") CA certificates"
echo "Mirrored from Android trust store: $(grep -c 'BEGIN CERTIFICATE' "$ANCHORS")"
echo "Manually added anchors: $(grep -c 'BEGIN CERTIFICATE' "$EXTRA")"

# Diagnose (but do not fail) so a blocked network still gets an actionable message in the log.
if curl -sS -m 25 -o /dev/null https://opencode.ai/ 2>/dev/null; then
    echo "HTTPS verification: OK"
else
    echo "HTTPS verification: FAILED - this network intercepts TLS with an untrusted CA."
    echo "  Fix: install your organization's root certificate on this device:"
    echo "    Settings > Security > Encryption & credentials > Install a certificate > CA certificate"
    echo "  then run setup again (or use a network without TLS inspection)."
fi
exit 0
